set -uo pipefail

# We use bash 4 features (${var,,} lowercasing, associative arrays). Every
# mainstream Linux ships bash >= 4; give a clear message instead of a cryptic
# parse error on an ancient bash.
if (( BASH_VERSINFO[0] < 4 )); then
    echo "ayneh: requires bash 4 or newer (you have ${BASH_VERSION})." >&2
    exit 1
fi

AYNEH_VERSION="2.1.0"
PROG="ayneh"
AYNEH_REPO="${AYNEH_REPO:-ihamedm/ayneh}"
AYNEH_BRANCH="${AYNEH_BRANCH:-main}"

# Where backups are stored. User-scope backups under HOME, system-scope under
# /var/backups.
USER_BACKUP_DIR="${HOME}/.ayneh-backup"
# Legacy location used by the 1.x script; still read so old backups work.
LEGACY_USER_BACKUP_DIR="${HOME}/.mirrors-backup"
SYS_BACKUP_DIR="/var/backups/ayneh"
LEGACY_SYS_BACKUP_DIR="/var/backups/mirrors"

# Probe timeouts (seconds). Override for slow links, e.g.
#   AYNEH_CONNECT_TIMEOUT=10 AYNEH_MAX_TIME=25 ayneh --scan
AYNEH_CONNECT_TIMEOUT="${AYNEH_CONNECT_TIMEOUT:-6}"
AYNEH_MAX_TIME="${AYNEH_MAX_TIME:-12}"

# Number of failed probes in the current scan (used for the summary line).
AYNEH_PROBE_FAILURES="${AYNEH_PROBE_FAILURES:-0}"

# -----------------------------------------------------------------------------
# Terminal colors (auto-disabled when not a tty, when NO_COLOR is set, or on a
# dumb terminal). Checked once.
# -----------------------------------------------------------------------------
if [[ -t 1 && "${TERM:-}" != "dumb" && -z "${NO_COLOR:-}" ]]; then
    C_RED=$'\033[31m';    C_GREEN=$'\033[32m';  C_YELLOW=$'\033[33m'
    C_BLUE=$'\033[34m';   C_MAGENTA=$'\033[35m'; C_CYAN=$'\033[36m'
    C_BOLD=$'\033[1m';    C_DIM=$'\033[2m';      C_OFF=$'\033[0m'
else
    C_RED=""; C_GREEN=""; C_YELLOW=""; C_BLUE=""; C_MAGENTA=""; C_CYAN=""
    C_BOLD=""; C_DIM=""; C_OFF=""
fi

# -----------------------------------------------------------------------------
# Logging helpers
# -----------------------------------------------------------------------------
info()  { printf '%s\n' "${C_CYAN}[i]${C_OFF} $*"; }
ok()    { printf '%s\n' "${C_GREEN}[+]${C_OFF} $*"; }
warn()  { printf '%s\n' "${C_YELLOW}[!]${C_OFF} $*"; }
err()   { printf '%s\n' "${C_RED}[x]${C_OFF} $*" >&2; }
die()   { err "$*"; exit 1; }
hdr()   { printf '\n%s\n' "${C_BOLD}${C_BLUE}=== $* ===${C_OFF}"; }

# -----------------------------------------------------------------------------
# Prompting
# -----------------------------------------------------------------------------

# Read one line from the controlling terminal. This is what makes the menu
# work even when the script was piped in via `curl ... | bash` (where stdin
# is the script body, not the keyboard).
ask() {
    local _var="$1"; shift
    printf '%s' "$*"
    local _rc
    # Open /dev/tty once instead of testing it with -r: in containers/CI it
    # can exist as a character device but still have no controlling terminal,
    # and the failed redirection itself would leak an error to stderr.
    if { exec 3</dev/tty; } 2>/dev/null; then
        # shellcheck disable=SC2229  # reading into a dynamically named variable
        IFS= read -r "$_var" <&3 2>/dev/null; _rc=$?
        exec 3<&-
    else
        # shellcheck disable=SC2229
        IFS= read -r "$_var" 2>/dev/null; _rc=$?
    fi
    # EOF (read returns non-zero): default to empty so callers never see an
    # unset value under `set -u`, and propagate the non-zero status so menu
    # loops can break instead of spinning forever on a closed stdin.
    [[ $_rc -ne 0 ]] && eval "$_var=''"
    return $_rc
}

confirm() {
    local prompt="$1" default="${2:-y}" yn
    if [[ "$default" =~ ^[Yy] ]]; then
        ask yn "${prompt} [Y/n] "
    else
        ask yn "${prompt} [y/N] "
    fi
    yn="${yn:-$default}"
    [[ "$yn" =~ ^[Yy] ]]
}

pause() {
    local _d
    ask _d "${C_DIM}— press Enter to continue —${C_OFF}"
}

# True when a controlling terminal is available (works even under curl | bash).
has_tty() {
    { : </dev/tty; } 2>/dev/null
}

# Clear the terminal between menu actions so each command starts on a clean
# screen. Only acts on a real terminal; AYNEH_NO_CLEAR=1 disables it.
clear_screen() {
    [[ "${AYNEH_NO_CLEAR:-0}" == "1" ]] && return 0
    [[ -t 1 ]] || return 0
    [[ "${TERM:-}" == "dumb" ]] && return 0
    if have tput && tput clear 2>/dev/null; then return 0; fi
    printf '\033[H\033[2J'
}

# -----------------------------------------------------------------------------
# Privileges
# -----------------------------------------------------------------------------
running_as_root() { [[ "${EUID:-$(id -u)}" -eq 0 ]]; }

# Run a command with sudo if we are not root, otherwise directly.
# Uses non-interactive sudo only (cached creds / NOPASSWD) so it never hangs
# or spews password errors in non-tty contexts. Callers that MUST have root
# should call require_root() first.
maybe_sudo() {
    if running_as_root; then "$@"; return $?; fi
    sudo -n "$@" 2>/dev/null; return $?
}

# Make sure we can use sudo, asking for a password on the controlling tty when
# needed (cached/NOPASSWD sudo returns immediately). This keeps the tool usable
# on a fresh server without forcing the user to prefix every command with sudo,
# while still working when the script is piped through `curl | bash`.
ensure_sudo() {
    running_as_root && return 0
    sudo -n true 2>/dev/null && return 0
    if [[ -r /dev/tty ]]; then
        printf '%s\n' "${C_DIM}Root privileges are needed; sudo may ask for your password.${C_OFF}" >/dev/tty
        if sudo -v; then
            return 0
        fi
    fi
    return 1
}

# Guard for system-scope applies: fail fast with a clear message instead of
# leaking sudo password errors mid-operation.
require_root() {
    local svc="$1" name="$2"
    if ensure_sudo; then return 0; fi
    err "This modifies system files and requires root (or passwordless sudo)."
    err "Re-run as:  sudo ayneh --apply ${svc} \"${name}\""
    return 1
}

# Real invoking user's HOME (when running under sudo).
real_home() {
    if [[ -n "${SUDO_USER:-}" ]]; then
        local h
        h="$(getent passwd "$SUDO_USER" 2>/dev/null | cut -d: -f6 || true)"
        [[ -n "$h" ]] && { printf '%s\n' "$h"; return 0; }
    fi
    printf '%s\n' "${HOME:-/root}"
}

have() { command -v "$1" >/dev/null 2>&1; }

# -----------------------------------------------------------------------------
# Scratch space (cleaned up on exit)
# -----------------------------------------------------------------------------
AYNEH_TMPDIR="${AYNEH_TMPDIR:-}"

ensure_tmpdir() {
    [[ -n "$AYNEH_TMPDIR" && -d "$AYNEH_TMPDIR" ]] && return 0
    AYNEH_TMPDIR="$(mktemp -d "${TMPDIR:-/tmp}/ayneh.XXXXXX")" || die "Could not create a temporary directory."
}

cleanup() {
    [[ -n "$AYNEH_TMPDIR" && -d "$AYNEH_TMPDIR" ]] && rm -rf "$AYNEH_TMPDIR"
    return 0
}

trap cleanup EXIT
trap 'cleanup; exit 130' INT
trap 'cleanup; exit 143' TERM
